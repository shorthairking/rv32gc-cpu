//==============================================================================
// rtl/exec/exe_ctrl.v —— E 级控制与旁路选择（纯组合，assign / function）
//==============================================================================
// 项目    : rv32gc-cpu（阶段二 2A：单发射顺序 5 级基线核）
// 依据    : docs/design/08-baseline-5stage.md §5.3 E 级表 —— `exe_ctrl.v`
//             「E 级控制与旁路选择」；
//             in: 各级结果与标签；out: 选中的操作数；
//             行为要点「旁路优先级」（负载结果的旁路见 §5.0 的 load-use 口径）。
//             ★★ 优先级取值已按**母 Agent 裁决（2026-09-14）**修正为
//                **M > W > 寄存器堆**：08 §5.3 原文的「W > M > 寄存器堆」
//                经裁定为**笔误**（详见下「优先级口径与裁决记录」），
//                规格本身由母 Agent 另派子 Agent 同步修正。
//           §5.0 冒险处理：「顺序 5 级核用**旁路网络 + 精确停顿**解决 RAW；
//             负载-使用冒险（load→use）在 2A 采用 **E/M 旁路 + 必要时停顿 1 拍**」。
//           AGENT.md §4 红线 3（禁止 `always @(*)` 给多个 reg 赋值）。
// 范围    : **寄存器堆读口在 core_top 集成**（本任务书明确口径）；
//             本模块**只做选择逻辑与接口**，不含寄存器堆本体、
//             不含停顿/冲刷的时序判定（那是 hazard unit / core_top 的职责）。
//==============================================================================
// 一、功能
//   为 E 级 ALU/BRU/MDU 准备两个源操作数（rs1/rs2）：
//     ① 从三个来源中按优先级选一个真正的值：
//          M 级（访存级结果，最高优先级）
//        > W 级（写回级结果）
//        > 寄存器堆读口（最低优先级，即无旁路时的默认值）
//     ② 同时给出各来源的"是否有有效写回标签"判定，供上层做停顿决策。
//
//   ---- 优先级口径与裁决记录 ----------------------------------------------------
//   **本文件实现 M > W > 寄存器堆**（母 Agent 裁决 2026-09-14）。
//
//   正确性论证（"更年轻者优先"）：
//     2A 顺序单发射核中，同一拍在途的指令序列是 [W 级提交中] → [M 级] → [E 级]，
//     即 **M 级指令比 W 级指令更年轻**（程序序上离 E 级更近）。
//     E 级正在消费的这条指令，其 rs 若被在途的多条指令写，则**程序序上最年轻
//     的那个定义者**持有的值才是架构正确值 ⇒ 更年轻的 M 级必须优先于 W 级。
//       * 若 M 与 W 都写同一 rd 且值不同，只有取 M 才正确。
//       * 若二者写不同 rd，优先级无影响（命中条件本就按 rd 号精确匹配）。
//       * E 级不可能自我保护（顺序核无 self-forward），故不参与比较。
//
//   ⚠ 规格笔误说明：`docs/design/08-baseline-5stage.md` §5.3 原文写作
//     「旁路优先级：**W > M > 寄存器堆**」，与上述语义论证矛盾。
//     母 Agent 于 **2026-09-14** 裁决：**原文为笔误**，正确口径为
//     **M > W > 寄存器堆**；规格将由母 Agent 另派子 Agent 同步修正。
//     本文件按裁决后的正确口径实现，并在本处留档裁决结论以便复核。
//
//   ⇒ 代码实现见下第 3 节的优先级链（**M 分支在前**）。
//
// 二、端口
//   ---- 寄存器号（来自 D 级译码，随指令流经 E 级） ----
//   rs1_addr [4:0]  : E 级指令的 rs1 寄存器号
//   rs2_addr [4:0]  : E 级指令的 rs2 寄存器号
//   ---- 各级写回标签与数据（"结果与标签"由上层流水寄存器送来） ----
//   w_valid         : W 级存在有效写回（提交拍或写回拍）
//   w_rd    [4:0]   : W 级写回目的寄存器号
//   w_data  [31:0]  : W 级写回数据
//   m_valid         : M 级存在有效写回
//   m_rd    [4:0]   : M 级目的寄存器号
//   m_data  [31:0]  : M 级结果数据
//   ---- 寄存器堆读口（**在 core_top 集成，此处只作为最低优先级输入**） ----
//   rf_rdata1 [31:0]: rs1 的寄存器堆读出值
//   rf_rdata2 [31:0]: rs2 的寄存器堆读出值
//   ---- 选中结果 ----
//   rs1     [31:0]  : 送给 ALU/BRU/MDU 的第一操作数
//   rs2     [31:0]  : 送给 ALU/BRU/MDU 的第二操作数
//   ---- 旁路命中指示（供 hazard 决策 / trace / 覆盖率统计） ----
//   fwd_rs1 [1:0]   : 00=无旁路(RF) 01=M 级 10=W 级 11=保留
//   fwd_rs2 [1:0]   : 同上
//
// 三、旁路命中条件（**必须排除 x0**）
//   * 写 x0 不产生任何架构效果 ⇒ `rd == 5'd0` 时**不得**旁路
//     （否则会把 0 以外的值灌进 x0 的消费者，破坏 "x0 恒 0" 语义）。
//   * 条件式：`valid && (rd != x0) && (rd == rs_addr)`
//   * **load-use 口径**（08 §5.0）：M 级若为 load 且 E 级立即使用其结果，
//     2A 采用「E/M 旁路 + 必要时停顿 1 拍」⇒ 本模块**照常给出 M 级旁路值**
//     （load 数据经 M 级流水寄存器送达即为有效），
//     是否停顿由 hazard 决策（core_top）依据 `fwd_*` 与实际访存完成时刻判定。
//     ⇒ 本模块**不做停顿**，只做选择（任务书口径）。
//
// 四、实现注记（红线 3 合规声明）
//   * **零 always 块、零 reg**：全部由 `function` + 连续 `assign` 表达
//     （AGENT.md §4 红线 3、08 §7.4）。
//   * 优先级用**嵌套三目**表达（W ? : M ? : RF），一眼可见优先级链；
//     等价的 case-if 写法会被综合成同一套优先级 mux。
//==============================================================================
`timescale 1ns / 1ps

`include "rtl/pkg/rv32_defs.vh"
`include "rtl/pkg/core_params.vh"

module exe_ctrl (
    // ---- E 级指令的源寄存器号 ----
    input  wire [4:0]  rs1_addr,      // E 级 rs1
    input  wire [4:0]  rs2_addr,      // E 级 rs2
    // ---- W 级写回（最高优先级） ----
    input  wire        w_valid,       // W 级有有效写回
    input  wire [4:0]  w_rd,          // W 级目的寄存器号
    input  wire [31:0] w_data,        // W 级写回数据
    // ---- M 级写回（次高优先级） ----
    input  wire        m_valid,       // M 级有有效结果
    input  wire [4:0]  m_rd,          // M 级目的寄存器号
    input  wire [31:0] m_data,        // M 级结果数据
    // ---- 寄存器堆读口（最低优先级；读口本体在 core_top） ----
    input  wire [31:0] rf_rdata1,     // rs1 的 RF 读出值
    input  wire [31:0] rf_rdata2,     // rs2 的 RF 读出值
    // ---- 选中后的操作数 ----
    output wire [31:0] rs1,           // 送 ALU/BRU/MDU 的第一操作数
    output wire [31:0] rs2,           // 送 ALU/BRU/MDU 的第二操作数
    // ---- 旁路命中指示（供 hazard 决策 / trace） ----
    output wire [1:0]  fwd_rs1,       // 00=RF 01=M 10=W
    output wire [1:0]  fwd_rs2        // 00=RF 01=M 10=W
);

    //--------------------------------------------------------------------------
    // 1. 常量：x0 编号与旁路来源编码
    //--------------------------------------------------------------------------
    localparam [4:0] X0_ADDR   = 5'd0;   // 零寄存器：写它不产生旁路

    localparam [1:0] FWD_RF     = 2'b00; // 无旁路：用寄存器堆读口
    localparam [1:0] FWD_M      = 2'b01; // M 级旁路
    localparam [1:0] FWD_W      = 2'b10; // W 级旁路

    //--------------------------------------------------------------------------
    // 2. 旁路命中判定（pure function，组合）
    //    条件：来源有效 && 目的寄存器不是 x0 && 目的寄存器号与本条 rs 相同
    //--------------------------------------------------------------------------
    function fw_hit;
        input        src_valid;    // 来源级 valid
        input [4:0]  src_rd;       // 来源级 rd
        input [4:0]  want_rs;      // 本条指令的 rs
        begin
            // ★ rd == x0 必须排除：写 x0 无效，旁路会破坏 "x0 恒 0"
            fw_hit = src_valid && (src_rd != X0_ADDR) && (src_rd == want_rs);
        end
    endfunction

    // 各级针对 rs1 / rs2 的命中
    wire hit_w_rs1 = fw_hit(w_valid, w_rd, rs1_addr);
    wire hit_w_rs2 = fw_hit(w_valid, w_rd, rs2_addr);
    wire hit_m_rs1 = fw_hit(m_valid, m_rd, rs1_addr);
    wire hit_m_rs2 = fw_hit(m_valid, m_rd, rs2_addr);

    //--------------------------------------------------------------------------
    // 3. 操作数选择（优先级链：**M > W > 寄存器堆**；母 Agent 裁决 2026-09-14）
    //    嵌套三目：**先测 M（最高，更年轻）**，再测 W，否则回落到 RF。
    //--------------------------------------------------------------------------
    assign rs1 = hit_m_rs1 ? m_data
               : hit_w_rs1 ? w_data
               :             rf_rdata1;

    assign rs2 = hit_m_rs2 ? m_data
               : hit_w_rs2 ? w_data
               :             rf_rdata2;

    //--------------------------------------------------------------------------
    // 4. 旁路命中指示（同一优先级链，编码与 FWD_* 一致）
    //    用途：① hazard 决策（load-use 是否停顿 1 拍）；
    //          ② 交付/验证侧统计旁路命中率（arch-test 覆盖率佐证）。
    //--------------------------------------------------------------------------
    assign fwd_rs1 = hit_m_rs1 ? FWD_M
                   : hit_w_rs1 ? FWD_W
                   :             FWD_RF;

    assign fwd_rs2 = hit_m_rs2 ? FWD_M
                   : hit_w_rs2 ? FWD_W
                   :             FWD_RF;

endmodule
