//==============================================================================
// sim/unit/tb_bru.sv —— rtl/exec/bru.v 单元测试（自检 TB，fail-closed）
//==============================================================================
// 目的    : 验证 E 级分支/跳转解析单元的条件判定与目标计算。
// 判据    : ① 进程退出码 0；② 输出末行恰为 `TB_BRU_UNIT: PASS`（唯一 PASS 字样）；
//           ③ 任何一条断言不符 ⇒ 立即 $fatal（非零退出码），且**绝不打印 PASS**。
// 纪律    : 08 §8.1「未捕获即失败」——显式计数器 + $fatal；
//           `$display` 仅用于诊断，判定一律走 $fatal / err_cnt。
// 覆盖    : 任务书验收判据③要求 ——
//             beq/bne/blt/bge/bltu/bgeu **真假两向**（各 2 条，共 12 条）
//             + jal / jalr 目标计算。
//           此外覆盖：jalr 的 bit0 强制清零、±溢出回绕、BR_NONE 不动控制流、
//                      jal 与 jalr 同时置位时 jal 优先（确定行为）。
// 顶层    : tb_bru（验收命令用 -s tb_bru）
// 说明    : 组合验证——DUT 无时钟；每条向量直接比对 taken/target。
//           br_op 编码（与 bru.v 头注「编码公约」一致）：
//             低 3 位 = BRANCH funct3；bit3 = jal；bit4 = jalr。
//==============================================================================
`timescale 1ns / 1ps

`include "rtl/pkg/rv32_defs.vh"
`include "rtl/pkg/core_params.vh"

module tb_bru;

    //--------------------------------------------------------------------------
    // 0. 检查计数器（fail-closed）
    //--------------------------------------------------------------------------
    integer chk_cnt = 0;
    integer err_cnt = 0;

    //--------------------------------------------------------------------------
    // 1. DUT 例化
    //--------------------------------------------------------------------------
    reg  [31:0] rs1, rs2, imm, pc;
    reg  [4:0]  br_op;
    wire        taken;
    wire [31:0] target;

    bru u_dut (
        .rs1    (rs1),
        .rs2    (rs2),
        .imm    (imm),
        .pc     (pc),
        .br_op  (br_op),
        .taken  (taken),
        .target (target)
    );

    //--------------------------------------------------------------------------
    // 2. br_op 编码镜像（**低 3 位 = BRANCH funct3**，与 pkg §3.4 一致）
    //--------------------------------------------------------------------------
    localparam [2:0] F3_BEQ  = `RV32GC_F3_BEQ;    // 000
    localparam [2:0] F3_BNE  = `RV32GC_F3_BNE;    // 001
    localparam [2:0] F3_BLT  = `RV32GC_F3_BLT;    // 100
    localparam [2:0] F3_BGE  = `RV32GC_F3_BGE;    // 101
    localparam [2:0] F3_BLTU = `RV32GC_F3_BLTU;   // 110
    localparam [2:0] F3_BGEU = `RV32GC_F3_BGEU;   // 111

    // ---- 跳转类型位（bru.v 中 is_jal = br_op[3]、is_jalr = br_op[4]） ----
    localparam [4:0] BR_IS_JAL  = 5'b01000;       // jal  ：bit3 = 1
    localparam [4:0] BR_IS_JALR = 5'b10000;       // jalr ：bit4 = 1
    //      （br_op[1:0] 恒 0 —— 跳转指令没有分支条件码）

    //--------------------------------------------------------------------------
    // 3. 检查任务
    //--------------------------------------------------------------------------
    task automatic chk;
        input [127:0] name;             // 诊断名
        input [4:0]   op;               // br_op
        input [31:0]  va, vb, vimm, vpc;
        input         exp_taken;
        input [31:0]  exp_target;
        begin
            br_op = op; rs1 = va; rs2 = vb; imm = vimm; pc = vpc;
            #1;
            chk_cnt = chk_cnt + 1;
            if ((taken !== exp_taken) || (target !== exp_target)) begin
                err_cnt = err_cnt + 1;
                $display("  [FAIL] %0s : op=%b rs1=%08h rs2=%08h imm=%08h pc=%08h",
                         name, op, va, vb, vimm, vpc);
                $display("         -> got taken=%b target=%08h ; exp taken=%b target=%08h",
                         taken, target, exp_taken, exp_target);
                $fatal(1, "TB_BRU_UNIT: FAIL");
            end
        end
    endtask

    //--------------------------------------------------------------------------
    // 4. 激励
    //--------------------------------------------------------------------------
    initial begin
        $display("=== tb_bru : rtl/exec/bru.v 单元测试开始 ===");

        //====================================================================
        // 4.1 BEQ：真假两向
        //====================================================================
        // 真：rs1 == rs2 ⇒ taken，target = pc + imm
        chk("beq_true" , {2'b00, F3_BEQ}, 32'h0000_1000, 32'h0000_1000, 32'h0000_0020,
            32'h1C00_0000, 1'b1, 32'h1C00_0020);
        // 真（全 1 相等）
        chk("beq_true_ff", {2'b00, F3_BEQ}, 32'hFFFF_FFFF, 32'hFFFF_FFFF, 32'h0000_0008,
            32'h1000_0000, 1'b1, 32'h1000_0008);
        // 假：rs1 != rs2 ⇒ 不跳，target 仍给 pc+imm（无副作用）
        chk("beq_false", {2'b00, F3_BEQ}, 32'h0000_1000, 32'h0000_1001, 32'h0000_0020,
            32'h1C00_0000, 1'b0, 32'h1C00_0020);
        // 假：0 vs -1（逐位比较，不做符号解释）
        chk("beq_false_sign", {2'b00, F3_BEQ}, 32'h0000_0000, 32'hFFFF_FFFF, 32'h0000_0004,
            32'h2000_0000, 1'b0, 32'h2000_0004);

        //====================================================================
        // 4.2 BNE：真假两向
        //====================================================================
        chk("bne_true" , {2'b00, F3_BNE}, 32'h0000_0001, 32'h0000_0002, 32'h0000_0010,
            32'h1C00_0100, 1'b1, 32'h1C00_0110);
        chk("bne_true_sign", {2'b00, F3_BNE}, 32'h0000_0000, 32'hFFFF_FFFF, 32'h0000_0004,
            32'h1C00_0000, 1'b1, 32'h1C00_0004);
        chk("bne_false", {2'b00, F3_BNE}, 32'hDEAD_BEEF, 32'hDEAD_BEEF, 32'h0000_0010,
            32'h1C00_0100, 1'b0, 32'h1C00_0110);
        chk("bne_false_zero", {2'b00, F3_BNE}, 32'h0000_0000, 32'h0000_0000, 32'h0000_0008,
            32'h0F00_0000, 1'b0, 32'h0F00_0008);

        //====================================================================
        // 4.3 BLT：**有符号**比较，真假两向
        //====================================================================
        // 真：-1 < 1（有符号）——若误用无符号比较会得假（关键反证点）
        chk("blt_true_neg", {2'b00, F3_BLT}, 32'hFFFF_FFFF, 32'h0000_0001, 32'h0000_0020,
            32'h1C00_0000, 1'b1, 32'h1C00_0020);
        // 真：INT_MIN < INT_MAX
        chk("blt_true_minmax", {2'b00, F3_BLT}, 32'h8000_0000, 32'h7FFF_FFFF, 32'h0000_0004,
            32'h1C00_0000, 1'b1, 32'h1C00_0004);
        // 假：1 < -1（有符号）为假
        chk("blt_false", {2'b00, F3_BLT}, 32'h0000_0001, 32'hFFFF_FFFF, 32'h0000_0020,
            32'h1C00_0000, 1'b0, 32'h1C00_0020);
        // 假：相等时 < 为假
        chk("blt_false_eq", {2'b00, F3_BLT}, 32'h1234_5678, 32'h1234_5678, 32'h0000_0008,
            32'h1C00_0000, 1'b0, 32'h1C00_0008);

        //====================================================================
        // 4.4 BGE：**有符号**比较，真假两向
        //====================================================================
        // 真：1 >= -1（有符号）
        chk("bge_true", {2'b00, F3_BGE}, 32'h0000_0001, 32'hFFFF_FFFF, 32'h0000_0010,
            32'h1C00_0000, 1'b1, 32'h1C00_0010);
        // 真：相等 ⇒ >= 为真
        chk("bge_true_eq", {2'b00, F3_BGE}, 32'hABCD_EF01, 32'hABCD_EF01, 32'h0000_0004,
            32'h1C00_0000, 1'b1, 32'h1C00_0004);
        // 假：-1 >= 1 为假（关键反证点：误用无符号会得真）
        chk("bge_false_neg", {2'b00, F3_BGE}, 32'hFFFF_FFFF, 32'h0000_0001, 32'h0000_0010,
            32'h1C00_0000, 1'b0, 32'h1C00_0010);
        // 假：INT_MIN >= INT_MAX 为假
        chk("bge_false_minmax", {2'b00, F3_BGE}, 32'h8000_0000, 32'h7FFF_FFFF, 32'h0000_0004,
            32'h1C00_0000, 1'b0, 32'h1C00_0004);

        //====================================================================
        // 4.5 BLTU：**无符号**比较，真假两向
        //====================================================================
        // 真：1 < 0xFFFF_FFFF（无符号）——若误用有符号会得假（关键反证点）
        chk("bltu_true", {2'b00, F3_BLTU}, 32'h0000_0001, 32'hFFFF_FFFF, 32'h0000_0020,
            32'h1C00_0000, 1'b1, 32'h1C00_0020);
        chk("bltu_true_zero", {2'b00, F3_BLTU}, 32'h0000_0000, 32'h8000_0000, 32'h0000_0004,
            32'h1C00_0000, 1'b1, 32'h1C00_0004);
        // 假：0xFFFF_FFFF < 1（无符号）为假
        chk("bltu_false", {2'b00, F3_BLTU}, 32'hFFFF_FFFF, 32'h0000_0001, 32'h0000_0020,
            32'h1C00_0000, 1'b0, 32'h1C00_0020);
        // 假：相等
        chk("bltu_false_eq", {2'b00, F3_BLTU}, 32'h8000_0000, 32'h8000_0000, 32'h0000_0008,
            32'h1C00_0000, 1'b0, 32'h1C00_0008);

        //====================================================================
        // 4.6 BGEU：**无符号**比较，真假两向
        //====================================================================
        // 真：0xFFFF_FFFF >= 1（无符号）
        chk("bgeu_true", {2'b00, F3_BGEU}, 32'hFFFF_FFFF, 32'h0000_0001, 32'h0000_0010,
            32'h1C00_0000, 1'b1, 32'h1C00_0010);
        // 真：相等
        chk("bgeu_true_eq", {2'b00, F3_BGEU}, 32'h8000_0000, 32'h8000_0000, 32'h0000_0004,
            32'h1C00_0000, 1'b1, 32'h1C00_0004);
        // 假：1 >= 0xFFFF_FFFF（无符号）为假（关键反证点：误用有符号会得真）
        chk("bgeu_false", {2'b00, F3_BGEU}, 32'h0000_0001, 32'hFFFF_FFFF, 32'h0000_0010,
            32'h1C00_0000, 1'b0, 32'h1C00_0010);
        chk("bgeu_false_hi", {2'b00, F3_BGEU}, 32'h7FFF_FFFF, 32'h8000_0000, 32'h0000_0004,
            32'h1C00_0000, 1'b0, 32'h1C00_0004);

        //====================================================================
        // 4.7 JAL：无条件跳转，target = pc + imm
        //====================================================================
        // J 型立即数 bit0 恒 0（ISA 保证）；此处验证 pc+imm 精确
        chk("jal_basic", BR_IS_JAL, 32'h0000_0000, 32'h0000_0000, 32'h0000_0100,
            32'h1C00_0000, 1'b1, 32'h1C00_0100);
        // jal 忽略 rs1/rs2（换 rs 值结果不变 —— 反证未误用 rs）
        chk("jal_ignore_rs", BR_IS_JAL, 32'hFFFF_FFFF, 32'hFFFF_FFFF, 32'h0000_0020,
            32'h1C00_0000, 1'b1, 32'h1C00_0020);
        // jal 负立即数（向后跳）：imm = 0xFFFF_FFF0 (=-16) ⇒ 0x1C00_0000 - 16
        chk("jal_backward", BR_IS_JAL, 32'h0000_0000, 32'h0000_0000, 32'hFFFF_FFF0,
            32'h1C00_0000, 1'b1, 32'h1BFF_FFF0);
        // jal 目标回绕（pc + imm 溢出 32 位）
        chk("jal_wrap", BR_IS_JAL, 32'h0000_0000, 32'h0000_0000, 32'hFFFF_FFF8,
            32'h0000_0004, 1'b1, 32'hFFFF_FFFC);

        //====================================================================
        // 4.8 JALR：target = (rs1 + imm) & ~1 —— **bit0 强制清零**
        //====================================================================
        // 奇数基址 ⇒ bit0 被清零
        chk("jalr_odd_base", BR_IS_JALR, 32'h0000_1001, 32'h0000_0000, 32'h0000_0004,
            32'h1C00_0000, 1'b1, 32'h0000_1004);
        // rs1 + imm 本身为奇数（0x1000 + 0x5 = 0x1005 ⇒ 清 bit0 ⇒ 0x1004）
        chk("jalr_odd_sum", BR_IS_JALR, 32'h0000_1000, 32'h0000_0000, 32'h0000_0005,
            32'h1C00_0000, 1'b1, 32'h0000_1004);
        // 偶数基址：不改变结果
        chk("jalr_even", BR_IS_JALR, 32'h0000_2000, 32'h0000_0000, 32'h0000_0008,
            32'h1C00_0000, 1'b1, 32'h0000_2008);
        // 负立即数 + 回绕：rs1=0x0000_0004, imm=0xFFFF_FFFF (=-1) ⇒ 0x0000_0003 ⇒ 清 bit0 ⇒ 0x0000_0002
        chk("jalr_neg_imm", BR_IS_JALR, 32'h0000_0004, 32'h0000_0000, 32'hFFFF_FFFF,
            32'h1C00_0000, 1'b1, 32'h0000_0002);
        // jal/jalr 忽略 rs2（换 rs2 结果不变 —— 反证未误用 rs2）
        chk("jalr_ignore_rs2", BR_IS_JALR, 32'h0000_3000, 32'hFFFF_FFFF, 32'h0000_0004,
            32'h1C00_0000, 1'b1, 32'h0000_3004);

        //====================================================================
        // 4.9 BR_NONE（非分支指令）：不改变控制流
        //====================================================================
        // 低位 3 位 = 000（会被当成 BEQ 的编码），但**没有 jal/jalr 位**时
        // 必须按"条件分支且条件为真"处理 —— 这正是 {2'b00, F3_BEQ} 的语义。
        // 因此 BR_NONE 用**保留的低位编码**（010，BRANCH 中不存在）表达：
        chk("none_f3_010", 5'b00010, 32'h0000_0001, 32'h0000_0001, 32'h0000_0010,
            32'h1C00_0000, 1'b0, 32'h1C00_0010);
        chk("none_f3_011", 5'b00011, 32'h0000_0001, 32'h0000_0001, 32'h0000_0010,
            32'h1C00_0000, 1'b0, 32'h1C00_0010);
        // 即使 rs1==rs2（"条件为真"），保留编码也**不得**触发重定向
        chk("none_must_not_taken", 5'b00010, 32'hAAAA_AAAA, 32'hAAAA_AAAA, 32'h0000_0020,
            32'h1C00_0000, 1'b0, 32'h1C00_0020);

        //====================================================================
        // 4.10 jal 与 jalr 同时置位：**jal 优先**（确定行为，译码不会产生）
        //====================================================================
        // jal 目标 = pc + imm；若误按 jalr 会得 (rs1+imm)&~1
        chk("jal_priority", 5'b11000, 32'h0000_9000, 32'h0000_0000, 32'h0000_0020,
            32'h1C00_0000, 1'b1, 32'h1C00_0020);

        //--------------------------------------------------------------------------
        // 5. 判定（fail-closed）
        //--------------------------------------------------------------------------
        if (chk_cnt == 0) begin
            $display("TB_BRU_UNIT: FAIL (no check executed)");
            $fatal(1, "TB_BRU_UNIT: FAIL");
        end
        if (err_cnt != 0) begin
            $display("TB_BRU_UNIT: FAIL (%0d/%0d checks failed)", err_cnt, chk_cnt);
            $fatal(1, "TB_BRU_UNIT: FAIL");
        end

        $display("TB_BRU_UNIT: checked %0d vectors, %0d errors", chk_cnt, err_cnt);
        $display("TB_BRU_UNIT: PASS");
        $finish(0);
    end

endmodule
